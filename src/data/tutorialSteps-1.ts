// Обучение разбито на несколько отдельных мини-туров вместо одного длинного
// (см. правку 2026-09-29): раньше тур за один присест вёл ребёнка через
// главный экран, ВСЕ разделы нижнего меню, кухню и копилку — это ощущалось
// как один долгий сплошной блок, оторванный от игры. Теперь:
//
//   - тур "home" — только сам главный экран (без переходов куда-либо),
//     запускается один раз при первом входе, как и раньше;
//   - у каждого раздела (уроки, периоды, магазин, рейтинг, кухня, копилка)
//     свой короткий тур из 1–2 шагов, который включается сам, когда ребёнок
//     САМ туда заходит в первый раз — неважно, ткнул ли он в раздел из
//     любопытства или его привело туда игровое событие (например, кухня —
//     после "покорми питомца"). Так объяснение приходит именно в момент,
//     когда оно нужно, а не всё разом в начале.
//
// Логика запуска — в features/tutorial/tutorialStore.ts (startIfNeeded для
// "home", startTourIfNeeded(tourId) для остальных, вызывается из самих
// экранов разделов при монтировании).
//
// Контент по-прежнему отделён от UI (см. ТЗ п. 3.2): здесь только тексты и
// то, КАКОЙ элемент подсвечивать. Сами элементы помечены в разметке
// атрибутом data-tour="<id>" — оверлей (components/TutorialOverlay.tsx)
// находит их по этому атрибуту, затемняет всё остальное и ставит рядом
// плашку.
//
// Тексты — от лица питомца, для детей 6+: коротко (1–2 простых
// предложения), без терминов. {name} подставляется именем питомца.

export type TutorialAction =
  /** показать карточку и кнопку "Дальше" */
  | 'next'
  /** ребёнок должен сам нажать на подсвеченный (настоящий) элемент */
  | 'tap';

export interface TutorialStep {
  id: string;
  /** data-tour id элементов; несколько — подсвечиваются одним общим окошком.
   *  Без targets — карточка по центру экрана (приветствие/финал). */
  targets?: string[];
  title: string;
  text: string;
  action: TutorialAction;
  /** картинка-сцена для центральных карточек */
  scene?: 'wave' | 'heart';
  /** подпись главной кнопки для action: 'next' */
  buttonLabel?: string;
  /** Для шагов, где нужно ПЕРЕТАЩИТЬ подсвеченный предмет ЗА пределы
   *  подсветки (например, еду — в рот питомцу): по умолчанию оверлей
   *  блокирует клики/тапы везде, кроме подсвеченной зоны, а тут это как
   *  раз мешает — сам путь перетаскивания лежит через затемнённую часть
   *  экрана. true снимает блокировку вне подсветки для этого шага (другие
   *  кнопки тура всё равно остаются недоступны — это отдельный, не
   *  геометрический механизм, см. TutorialOverlay). */
  freeInteraction?: boolean;
}


// touch: 2026-09-26 — обновлено под текущую версию приложения:
//   - кнопка "Гардероб" с главного экрана убрана (сам экран временно не
//     открывается никем, см. комментарий в Home.tsx) — шаги про гардероб
//     из тура удалены, чтобы не подсвечивать несуществующую кнопку;
//   - вкладка нижнего меню "День" (календарик) теперь открывает новый
//     экран "Периоды" (сюжетные периоды с планированием бюджета и
//     событиями) вместо старого списка заданий дня — контент шагов под
//     эту вкладку переписан заново.
//
// Контент отделён от UI (см. ТЗ п. 3.2): здесь только тексты и то, КАКОЙ
// элемент подсвечивать. Сами элементы помечены в разметке атрибутом
// data-tour="<id>" — оверлей (components/TutorialOverlay.tsx) находит их
// по этому атрибуту, затемняет всё остальное и ставит рядом плашку.
//
// Порядок обхода: сначала главный экран целиком (что где на нём),
// затем разделы нижнего меню (уроки → периоды → магазин → рейтинг),
// затем кухня, затем копилка — то есть каждый раз доходим до места,
// коротко объясняем и возвращаемся, прежде чем идти дальше.
//
// Тексты — от лица питомца, для детей 6+: коротко (1–2 простых
// предложения), без терминов. {name} подставляется именем питомца.

export type TutorialAction =
  /** показать карточку и кнопку "Дальше" */
  | 'next'
  /** ребёнок должен сам нажать на подсвеченный (настоящий) элемент */
  | 'tap';

export interface TutorialStep {
  id: string;
  /** data-tour id элементов; несколько — подсвечиваются одним общим окошком.
   *  Без targets — карточка по центру экрана (приветствие/финал). */
  targets?: string[];
  title: string;
  text: string;
  action: TutorialAction;
  /** картинка-сцена для центральных карточек */
  scene?: 'wave' | 'heart';
  /** подпись главной кнопки для action: 'next' */
  buttonLabel?: string;
  /** Для шагов, где нужно ПЕРЕТАЩИТЬ подсвеченный предмет ЗА пределы
   *  подсветки (например, еду — в рот питомцу): по умолчанию оверлей
   *  блокирует клики/тапы везде, кроме подсвеченной зоны, а тут это как
   *  раз мешает — сам путь перетаскивания лежит через затемнённую часть
   *  экрана. true снимает блокировку вне подсветки для этого шага (другие
   *  кнопки тура всё равно остаются недоступны — это отдельный, не
   *  геометрический механизм, см. TutorialOverlay). */
  freeInteraction?: boolean;
}

